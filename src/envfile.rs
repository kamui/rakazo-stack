    #[test]
    fn writes_the_chat_model_for_openrouter_and_anthropic_only() {
        let key = PastedKey::new("placeholder-key").unwrap();
        let rakazo = release();
        for provider in Provider::ALL {
            let mut secrets = Secrets::default();
            secrets.fill_missing(|n| "ab".repeat(n));
            model_provider::save_key(&mut secrets, Some((provider, &key)));
            let text = render(&EnvInputs {
                project: "rakazo-stack",
                rakazo: &rakazo,
                lemonade: None,
                secrets: &secrets,
                web_port: 5173,
                chat: ChatModel::new(provider, &key, None).unwrap(),
                addresses: &Access::Localhost.addresses(None, 5173),
                tailscale: None,
                memory: None,
            });
            let model: Vec<&str> = text
                .lines()
                .filter(|l| l.starts_with("PI_") || l.contains("_API_KEY="))
                .filter(|l| !l.starts_with("LEMONADE_API_KEY="))
                .filter(|l| *l != "COMPOSIO_API_KEY=")
                .collect();
            let expected: &[&str] = match provider {
                Provider::OpenRouter => &[
                    "PI_DEFAULT_PROVIDER=openrouter",
                    "OPENROUTER_API_KEY=placeholder-key",
                    "PI_DEFAULT_MODEL=~z-ai/glm-flash-latest",
                ],
                Provider::Anthropic => &[
                    "PI_DEFAULT_PROVIDER=anthropic",
                    "ANTHROPIC_API_KEY=placeholder-key",
                    "PI_DEFAULT_MODEL=claude-haiku-5-5",
                ],
                Provider::OpenAi | Provider::Gemini => &[],
            };
            assert!(model == expected, "{provider:?}");
            assert!(text.lines().any(|l| l == "COMPOSE_PROFILES="));
            assert!(!text.contains("LEMONADE_IMAGE"));
            for never in [
                "OPENAI_API_KEY",
                "GEMINI_API_KEY",
                "RAKAZO_MIN_CLIENT_BUILD",
                "EXPO_ACCESS_TOKEN",
            ] {
                assert!(!text.contains(never), "{provider:?} writes {never}");
            }
        }
    }

    #[test]
    fn memory_turns_the_hindsight_profile_on_beside_tailscale() {
        let key = PastedKey::new("placeholder-key").unwrap();
        let hindsight = crate::resolve::HindsightRelease {
            version: "1.3.0".into(),
            digest: "sha256:hhh".into(),
            db_digest: "sha256:ddd".into(),
        };
        let image = RecordedImage {
            version: "v1.104.7".into(),
            digest: "sha256:ttt".into(),
        };
        let mut secrets = Secrets::default();
        secrets.fill_missing(|n| "ab".repeat(n));
        secrets.fill_missing_hindsight(|n| "cd".repeat(n));
        let memory = || MemoryEnv {
            release: &hindsight,
            model: crate::memory::HindsightModel::new(Provider::OpenAi, &key, None).unwrap(),
            secrets: &secrets,
        };
        let render_with = |tailscale| {
            render(&EnvInputs {
                project: "rakazo-stack",
                rakazo: &release(),
                lemonade: None,
                secrets: &secrets,
                web_port: 5173,
                chat: None,
                addresses: &Access::Localhost.addresses(None, 5173),
                tailscale,
                memory: Some(memory()),
            })
        };
        let text = render_with(None);
        assert_lines(
            &text,
            &[
                "COMPOSE_PROFILES=hindsight",
                "HINDSIGHT_IMAGE_TAG=1.3.0@sha256:hhh",
                "HINDSIGHT_API_LLM_PROVIDER=openai",
                "HINDSIGHT_API_LLM_API_KEY=placeholder-key",
            ],
        );
        assert!(
            !text.contains("OPENAI_API_KEY="),
            "Rakazo's env never gets OpenAI's key"
        );
        let both = render_with(Some(TailscaleEnv {
            image: &image,
            device_name: "rakazo",
            auth_key: None,
        }));
        assert_lines(&both, &["COMPOSE_PROFILES=hindsight,tailscale"]);
    }
