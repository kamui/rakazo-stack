//! Renders `.env`, the file Compose reads, from `settings.json` and `secrets.env`
//! (spec §5, "Rakazo settings setup writes to `.env`").

use crate::resolve::RakazoRelease;
use crate::secrets::Secrets;

pub struct EnvInputs<'a> {
    pub project: &'a str,
    pub rakazo: &'a RakazoRelease,
    pub secrets: &'a Secrets,
    pub web_port: u16,
}

pub fn rakazo_compose_file(tag: &str) -> String {
    format!("rakazo.{tag}.images.yml")
}

pub const STACK_COMPOSE_FILE: &str = "compose.stack.yaml";

pub fn render(inputs: &EnvInputs) -> String {
    let origin = format!("http://127.0.0.1:{}", inputs.web_port);
    let tag = &inputs.rakazo.tag;
    let mut lines = vec![
        "# Generated by rakazo-stack setup. Edits are overwritten; run `rakazo-stack setup` to change settings.".to_string(),
        format!("COMPOSE_PROJECT_NAME={}", inputs.project),
        format!(
            "COMPOSE_FILE={}:{STACK_COMPOSE_FILE}",
            rakazo_compose_file(tag)
        ),
        // docker.exe would otherwise split COMPOSE_FILE on Windows' `;`.
        "COMPOSE_PATH_SEPARATOR=:".to_string(),
        format!("RAKAZO_IMAGE_TAG={tag}@{}", inputs.rakazo.app_digest),
        format!(
            "RAKAZO_COMPUTER_IMAGE_TAG={tag}@{}",
            inputs.rakazo.computer_digest
        ),
    ];
    for (key, value) in inputs.secrets.rakazo() {
        lines.push(format!("{key}={value}"));
    }
    lines.extend([
        "SIGNUPS_ENABLED=false".to_string(),
        "SANDBOX_COMPUTER_EGRESS=restricted".to_string(),
        format!("RAKAZO_WEB_PORT={}", inputs.web_port),
        format!("BETTER_AUTH_URL={origin}"),
        format!("WEB_ORIGIN={origin}"),
        format!("API_URL={origin}"),
        "RAKAZO_HOST=127.0.0.1".to_string(),
    ]);
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_the_localhost_slice() {
        let mut secrets = Secrets::default();
        secrets.fill_missing(|n| "ab".repeat(n));
        let rakazo = RakazoRelease {
            tag: "v0.16.0".into(),
            app_digest: "sha256:aaa".into(),
            computer_digest: "sha256:ccc".into(),
        };
        let text = render(&EnvInputs {
            project: "rakazo-stack",
            rakazo: &rakazo,
            secrets: &secrets,
            web_port: 5173,
        });
        for line in [
            "COMPOSE_PROJECT_NAME=rakazo-stack",
            "COMPOSE_FILE=rakazo.v0.16.0.images.yml:compose.stack.yaml",
            "RAKAZO_IMAGE_TAG=v0.16.0@sha256:aaa",
            "RAKAZO_COMPUTER_IMAGE_TAG=v0.16.0@sha256:ccc",
            "SIGNUPS_ENABLED=false",
            "SANDBOX_COMPUTER_EGRESS=restricted",
            "BETTER_AUTH_URL=http://127.0.0.1:5173",
            "WEB_ORIGIN=http://127.0.0.1:5173",
            "API_URL=http://127.0.0.1:5173",
            "RAKAZO_HOST=127.0.0.1",
        ] {
            assert!(text.lines().any(|l| l == line), "missing {line}");
        }
        assert_eq!(
            text.lines()
                .filter(|l| l.starts_with("POSTGRES_") || l.contains("_SECRET="))
                .count(),
            4
        );
        assert!(!text.contains("updater"));
    }
}
