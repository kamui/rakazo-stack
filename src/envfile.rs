//! Renders `.env`, the file Compose reads, from `settings.json` and `secrets.env`
//! (spec §5, "Rakazo settings setup writes to `.env`").

use crate::access::{AUTH_KEY_NAME, Addresses};
use crate::composio;
use crate::lemonade::LemonadeRelease;
use crate::model_provider::ChatModel;
use crate::resolve::RakazoRelease;
use crate::secrets::{LEMONADE_API_KEY, Secrets};
use crate::settings::RecordedImage;
use crate::tailscale;

pub struct EnvInputs<'a> {
    pub project: &'a str,
    pub rakazo: &'a RakazoRelease,
    /// The `lemonade` container's release; `None` where Lemonade runs natively.
    pub lemonade: Option<&'a LemonadeRelease>,
    pub secrets: &'a Secrets,
    pub web_port: u16,
    /// The Instance-wide chat model; without one, each person connects their own.
    pub chat: Option<ChatModel<'a>>,
    pub addresses: &'a Addresses,
    /// `Some` turns the `tailscale` profile on.
    pub tailscale: Option<TailscaleEnv<'a>>,
}

pub struct TailscaleEnv<'a> {
    pub image: &'a RecordedImage,
    pub device_name: &'a str,
    /// Written only until the Instance has joined.
    pub auth_key: Option<&'a str>,
}

pub fn rakazo_compose_file(tag: &str) -> String {
    format!("rakazo.{tag}.images.yml")
}

pub const STACK_COMPOSE_FILE: &str = "compose.stack.yaml";

pub fn render(inputs: &EnvInputs) -> String {
    let tag = &inputs.rakazo.tag;
    let mut lines = vec![
        "# Generated by rakazo-stack setup. Edits are overwritten; run `rakazo-stack setup` to change settings.".to_string(),
        format!("COMPOSE_PROJECT_NAME={}", inputs.project),
        format!(
            "COMPOSE_FILE={}:{STACK_COMPOSE_FILE}",
            rakazo_compose_file(tag)
        ),
        // docker.exe would otherwise split COMPOSE_FILE on Windows' `;`.
        "COMPOSE_PATH_SEPARATOR=:".to_string(),
        format!(
            "COMPOSE_PROFILES={}",
            [
                inputs.lemonade.map(|_| "lemonade"),
                inputs.tailscale.as_ref().map(|_| tailscale::SERVICE),
            ]
            .into_iter()
            .flatten()
            .collect::<Vec<_>>()
            .join(",")
        ),
        format!("RAKAZO_IMAGE_TAG={tag}@{}", inputs.rakazo.app_digest),
        format!(
            "RAKAZO_COMPUTER_IMAGE_TAG={tag}@{}",
            inputs.rakazo.computer_digest
        ),
    ];
    for (key, value) in inputs.secrets.rakazo() {
        lines.push(format!("{key}={value}"));
    }
    if let Some(lemonade) = inputs.lemonade {
        lines.push(format!("LEMONADE_IMAGE={}", lemonade.image()));
    }
    if let Some(key) = inputs.secrets.get(LEMONADE_API_KEY.0) {
        lines.push(format!("{}={key}", LEMONADE_API_KEY.0));
    }
    lines.extend([
        "SIGNUPS_ENABLED=false".to_string(),
        "PHONE_CALLS_ENABLED=true".to_string(),
        // Lets Rakazo reach the relay by its service name (spec §9).
        "MCP_ALLOW_PRIVATE_ENDPOINT=true".to_string(),
        "RAKAZO_OPENAI_COMPAT_PRIVATE_HOSTS=lemonade-relay".to_string(),
        "SANDBOX_COMPUTER_EGRESS=restricted".to_string(),
        format!("RAKAZO_WEB_PORT={}", inputs.web_port),
        format!("BETTER_AUTH_URL={}", inputs.addresses.better_auth_url),
        format!("WEB_ORIGIN={}", inputs.addresses.web_origin),
        format!("API_URL={}", inputs.addresses.api_url),
        format!("RAKAZO_HOST={}", inputs.addresses.rakazo_host),
    ]);
    if let Some(chat) = &inputs.chat {
        lines.extend([
            format!("PI_DEFAULT_PROVIDER={}", chat.provider.id()),
            format!("{}={}", chat.provider.key_name(), chat.key.expose()),
            format!("PI_DEFAULT_MODEL={}", chat.model),
        ]);
    }
    // Blank turns integrations off.
    let composio_key = inputs.secrets.get(composio::KEY_NAME).unwrap_or_default();
    lines.push(format!("{}={composio_key}", composio::KEY_NAME));
    if let Some(tailscale) = &inputs.tailscale {
        let image = tailscale.image;
        lines.push(format!(
            "TAILSCALE_IMAGE_TAG={}@{}",
            image.version, image.digest
        ));
        lines.push(format!("TS_HOSTNAME={}", tailscale.device_name));
        if let Some(key) = tailscale.auth_key {
            lines.push(format!("{AUTH_KEY_NAME}={key}"));
        }
    }
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::access::{Access, DeviceName, InstanceUrl};
    use crate::model_provider::{self, Provider};
    use crate::secrets::PastedKey;

    fn release() -> RakazoRelease {
        RakazoRelease {
            tag: "v0.16.0".into(),
            app_digest: "sha256:aaa".into(),
            computer_digest: "sha256:ccc".into(),
        }
    }

    fn rendered(access: &Access, dns_name: Option<&str>, auth_key: Option<&str>) -> String {
        let mut secrets = Secrets::default();
        secrets.fill_missing(|n| "ab".repeat(n));
        // A saved key reaches `.env` only through `TailscaleEnv`.
        let saved = PastedKey::new("tskey-auth-kSAVED").unwrap();
        secrets.set_pasted(AUTH_KEY_NAME, Some(&saved));
        let image = RecordedImage {
            version: "v1.104.7".into(),
            digest: "sha256:ttt".into(),
        };
        let lemonade = LemonadeRelease {
            tag: "v2026.48.3".into(),
            digest: "sha256:lll".into(),
        };
        render(&EnvInputs {
            project: "rakazo-stack",
            rakazo: &release(),
            lemonade: Some(&lemonade),
            secrets: &secrets,
            web_port: 5173,
            chat: None,
            addresses: &access.addresses(dns_name, 5173),
            tailscale: matches!(access, Access::Tailscale { .. }).then_some(TailscaleEnv {
                image: &image,
                device_name: "rakazo-1",
                auth_key,
            }),
        })
    }

    fn assert_lines(text: &str, expected: &[&str]) {
        for line in expected {
            assert!(text.lines().any(|l| l == *line), "missing {line}:\n{text}");
        }
    }

    #[test]
    fn renders_the_localhost_slice() {
        let text = rendered(&Access::Localhost, None, None);
        assert!(!text.contains("PI_DEFAULT"));
        assert!(
            text.lines()
                .filter(|l| l.contains("_API_KEY"))
                .all(|l| l.starts_with("LEMONADE_API_KEY=") || l == "COMPOSIO_API_KEY="),
            "only Lemonade's key without a Model provider or integrations"
        );
        assert!(!text.contains("TS_") && !text.contains("TAILSCALE"));
        assert!(!text.contains("tskey"));
        assert_lines(
            &text,
            &[
                "COMPOSE_PROJECT_NAME=rakazo-stack",
                "COMPOSE_FILE=rakazo.v0.16.0.images.yml:compose.stack.yaml",
                "COMPOSE_PROFILES=lemonade",
                "LEMONADE_IMAGE=ghcr.io/lemonade-sdk/lemonade-server:v2026.48.3@sha256:lll",
                "PHONE_CALLS_ENABLED=true",
                "MCP_ALLOW_PRIVATE_ENDPOINT=true",
                "RAKAZO_OPENAI_COMPAT_PRIVATE_HOSTS=lemonade-relay",
                "RAKAZO_IMAGE_TAG=v0.16.0@sha256:aaa",
                "RAKAZO_COMPUTER_IMAGE_TAG=v0.16.0@sha256:ccc",
                "SIGNUPS_ENABLED=false",
                "SANDBOX_COMPUTER_EGRESS=restricted",
                "COMPOSIO_API_KEY=",
                "BETTER_AUTH_URL=http://127.0.0.1:5173",
                "WEB_ORIGIN=http://127.0.0.1:5173",
                "API_URL=http://127.0.0.1:5173",
                "RAKAZO_HOST=127.0.0.1",
            ],
        );
        assert_eq!(
            text.lines()
                .filter(|l| l.starts_with("POSTGRES_") || l.contains("_SECRET="))
                .count(),
            4
        );
        assert!(!text.contains("updater"));
        assert_eq!(
            text.lines()
                .filter(|l| l.starts_with("LEMONADE_API_KEY=") && l.len() > 60)
                .count(),
            1
        );
    }

    #[test]
    fn renders_a_first_tailscale_join_on_localhost() {
        let access = Access::Tailscale {
            device_name: DeviceName::parse("rakazo").unwrap(),
            auth_key: None,
        };
        let text = rendered(&access, None, Some("tskey-auth-kPLACEHOLDER"));
        assert_lines(
            &text,
            &[
                "COMPOSE_PROFILES=lemonade,tailscale",
                "TAILSCALE_IMAGE_TAG=v1.104.7@sha256:ttt",
                "TS_HOSTNAME=rakazo-1",
                "TS_AUTHKEY=tskey-auth-kPLACEHOLDER",
                "BETTER_AUTH_URL=http://127.0.0.1:5173",
                "WEB_ORIGIN=http://127.0.0.1:5173",
                "API_URL=http://127.0.0.1:5173",
                "RAKAZO_HOST=127.0.0.1",
            ],
        );
    }

    #[test]
    fn renders_a_joined_instance_without_a_key() {
        let access = Access::Tailscale {
            device_name: DeviceName::parse("rakazo-1").unwrap(),
            auth_key: None,
        };
        let text = rendered(&access, Some("rakazo-1.example.ts.net"), None);
        assert_lines(
            &text,
            &[
                "COMPOSE_PROFILES=lemonade,tailscale",
                "BETTER_AUTH_URL=http://127.0.0.1:5173",
                "WEB_ORIGIN=https://rakazo-1.example.ts.net",
                "API_URL=https://rakazo-1.example.ts.net",
                "RAKAZO_HOST=rakazo-1.example.ts.net",
            ],
        );
        assert!(!text.contains("TS_AUTHKEY") && !text.contains("tskey"));
    }

    #[test]
    fn renders_a_bring_your_own_url() {
        let url = InstanceUrl::parse("https://rakazo.example.com").unwrap();
        let text = rendered(&Access::BringYourOwn(url), None, None);
        assert_lines(
            &text,
            &[
                "COMPOSE_PROFILES=lemonade",
                "BETTER_AUTH_URL=https://rakazo.example.com",
                "WEB_ORIGIN=https://rakazo.example.com",
                "API_URL=https://rakazo.example.com",
                "RAKAZO_HOST=rakazo.example.com",
                "RAKAZO_WEB_PORT=5173",
            ],
        );
        assert!(!text.contains("RAKAZO_WEB_BIND"), "web stays on 127.0.0.1");
    }

    #[test]
    fn writes_the_saved_composio_key() {
        let mut secrets = Secrets::default();
        secrets.set_pasted(
            composio::KEY_NAME,
            PastedKey::new("placeholder-key").as_ref(),
        );
        let text = render(&EnvInputs {
            project: "rakazo-stack",
            rakazo: &release(),
            lemonade: None,
            secrets: &secrets,
            web_port: 5173,
            chat: None,
            addresses: &Access::Localhost.addresses(None, 5173),
            tailscale: None,
        });
        assert_lines(&text, &["COMPOSIO_API_KEY=placeholder-key"]);
    }

    #[test]
    fn writes_the_chat_model_for_openrouter_and_anthropic_only() {
        let key = PastedKey::new("placeholder-key").unwrap();
        let rakazo = release();
        for provider in Provider::ALL {
            let mut secrets = Secrets::default();
            secrets.fill_missing(|n| "ab".repeat(n));
            model_provider::save_key(&mut secrets, Some((provider, &key)));
            let text = render(&EnvInputs {
                project: "rakazo-stack",
                rakazo: &rakazo,
                lemonade: None,
                secrets: &secrets,
                web_port: 5173,
                chat: ChatModel::new(provider, &key, None).unwrap(),
                addresses: &Access::Localhost.addresses(None, 5173),
                tailscale: None,
            });
            let model: Vec<&str> = text
                .lines()
                .filter(|l| l.starts_with("PI_") || l.contains("_API_KEY="))
                .filter(|l| !l.starts_with("LEMONADE_API_KEY="))
                .filter(|l| *l != "COMPOSIO_API_KEY=")
                .collect();
            let expected: &[&str] = match provider {
                Provider::OpenRouter => &[
                    "PI_DEFAULT_PROVIDER=openrouter",
                    "OPENROUTER_API_KEY=placeholder-key",
                    "PI_DEFAULT_MODEL=~z-ai/glm-flash-latest",
                ],
                Provider::Anthropic => &[
                    "PI_DEFAULT_PROVIDER=anthropic",
                    "ANTHROPIC_API_KEY=placeholder-key",
                    "PI_DEFAULT_MODEL=claude-haiku-5-5",
                ],
                Provider::OpenAi | Provider::Gemini => &[],
            };
            assert!(model == expected, "{provider:?}");
            assert!(text.lines().any(|l| l == "COMPOSE_PROFILES="));
            assert!(!text.contains("LEMONADE_IMAGE"));
            for never in [
                "OPENAI_API_KEY",
                "GEMINI_API_KEY",
                "RAKAZO_MIN_CLIENT_BUILD",
                "EXPO_ACCESS_TOKEN",
            ] {
                assert!(!text.contains(never), "{provider:?} writes {never}");
            }
        }
    }
}
